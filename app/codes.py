# 内水（自治体データ・メートル値）の深さ区分。表示用。
NAISUI_BANDS = [(0.0, 0.3, '0.3m未満'), (0.3, 0.5, '0.3m以上0.5m未満'), (0.5, 1.0, '0.5m以上1.0m未満'),
                (1.0, 2.0, '1.0m以上2.0m未満'), (2.0, 3.0, '2.0m以上3.0m未満'), (3.0, 99.0, '3.0m以上')]


def naisui_band(depth_m):
    if depth_m is None:
        return None
    for lo, hi, label in NAISUI_BANDS:
        if lo <= depth_m < hi:
            return label
    return NAISUI_BANDS[-1][2]


def minutes_label(m):
    if m is None:
        return None
    m = float(m)
    if m < 60:
        return f'約{int(round(m))}分'
    if m < 60 * 24:
        return f'約{m / 60:.0f}時間'
    return f'約{m / 60 / 24:.1f}日'
