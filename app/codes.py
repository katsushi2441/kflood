def naisui_band(depth_m, scheme='fine'):
    """深さ(m)→区分ラベル。'gsi'=重ねるハザードマップ、'a49'=国土数値情報の高潮の区分で読む。"""
    if depth_m is None:
        return None
    bands = {'gsi': GSI_NAISUI_BANDS, 'a49': A49_TAKASHIO_BANDS}.get(scheme, NAISUI_BANDS)
    for lo, hi, label in bands:
        if lo <= depth_m < hi:
            return label
    return bands[-1][2]


def depth_rank(depth_m):
    """浸水深(m)→ DEPTH_RANK のランク。自治体データ（メートル値）を国のランクに揃えるため。"""
    if depth_m is None:
        return None
    for rank, hi in ((1, 0.5), (2, 3.0), (3, 5.0), (4, 10.0), (5, 20.0)):
        if depth_m < hi:
            return rank
    return 6


def duration_rank(minutes):
    """浸水継続時間(分)→ DURATION_RANK のランク（12・24・72・168・336・672時間で区切る）。"""
    if minutes is None:
        return None
    h = float(minutes) / 60
    for rank, hi in ((1, 12), (2, 24), (3, 72), (4, 168), (5, 336), (6, 672)):
        if h < hi:
            return rank
    return 7


def minutes_label(m):
    if m is None:
        return None
    m = float(m)
    if m < 60:
        return f'約{int(round(m))}分'
    if m < 60 * 24:
        return f'約{m / 60:.0f}時間'
    return f'約{m / 60 / 24:.1f}日'
